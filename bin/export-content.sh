#!/usr/bin/env bash
# Exports the live site's pages and template parts into content/, the files
# Activator reads on activation: atelier-page.html (landing), pages.json (every
# page under /atelier: path, title, template, parents first) with
# pages/{path}.html (e.g. pages/pure/adesao.html), header-part.html /
# footer-part.html, media/ + media.json (images the content uses) and
# navigation/ + navigation.json (menus its navigation blocks reference). Also
# regenerates the axell/form-atelier template.ts. Run from anywhere while the Studio site is running. The database is the source of
# truth; this only copies it into the repository.
set -euo pipefail

PLUGIN_DIR="$(cd "$(dirname "$0")/.." && pwd)"
SITE_DIR="$(cd "$PLUGIN_DIR/../../.." && pwd)"

PHP="$(cat <<'PHP'
$dir = AXELLCORE_ATELIERCLUB_PATH . 'content/';
$landing = get_page_by_path( 'atelier', OBJECT, 'page' );
if ( ! $landing ) { echo "landing not found\n"; return; }
file_put_contents( $dir . 'atelier-page.html', $landing->post_content );
echo "atelier-page.html\n";
// Every page under /atelier, parents first, by its path below /atelier.
$pages_dir = $dir . 'pages/';
foreach ( glob( $pages_dir . '{*.html,*/*.html,*/*/*.html}', GLOB_BRACE ) as $stale ) {
	unlink( $stale );
}
$manifest = array();
$walk     = function ( $parent_id, $prefix ) use ( &$walk, &$manifest, $pages_dir ) {
	$children = get_posts( array( 'post_type' => 'page', 'post_parent' => $parent_id, 'post_status' => array( 'publish', 'private', 'draft' ), 'numberposts' => -1, 'orderby' => 'menu_order title', 'order' => 'ASC' ) );
	foreach ( $children as $child ) {
		$path = $prefix . $child->post_name;
		$file = $pages_dir . $path . '.html';
		if ( ! is_dir( dirname( $file ) ) ) {
			mkdir( dirname( $file ), 0755, true );
		}
		file_put_contents( $file, $child->post_content );
		$manifest[] = array(
			'path'     => $path,
			'title'    => $child->post_title,
			'template' => (string) get_page_template_slug( $child ),
		);
		echo 'pages/' . $path . ".html\n";
		$walk( $child->ID, $path . '/' );
	}
};
$walk( $landing->ID, '' );
file_put_contents( $dir . 'pages.json', wp_json_encode( $manifest, JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES ) . "\n" );
echo "pages.json\n";

// Template of axell/form-atelier: the inner blocks of the atelier form on
// /atelier/pure/adesao, serialized into src/form/form-atelier/template.ts (the
// default content of the block; run npm run build afterwards).
$template_page = get_page_by_path( 'atelier/pure/adesao', OBJECT, 'page' );
$find_form     = function ( $blocks ) use ( &$find_form ) {
	foreach ( $blocks as $block ) {
		if ( 'axell/form-atelier' === $block['blockName'] ) {
			return $block;
		}
		if ( ! empty( $block['innerBlocks'] ) ) {
			$found = $find_form( $block['innerBlocks'] );
			if ( $found ) {
				return $found;
			}
		}
	}
	return null;
};
$atelier_form = $template_page ? $find_form( parse_blocks( $template_page->post_content ) ) : null;
if ( $atelier_form ) {
	$markup = serialize_blocks( $atelier_form['innerBlocks'] );
	$ts     = "/**\n * Default content of axell/form-atelier: the inner blocks of the atelier\n * form on /atelier/pure/adesao. Generated by bin/export-content.sh from the\n * database; do not edit by hand (edit the page, export, then build).\n */\nexport const ATELIER_TEMPLATE = " . wp_json_encode( $markup, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES ) . ";\n";
	file_put_contents( AXELLCORE_ATELIERCLUB_PATH . 'src/form/form-atelier/template.ts', $ts );
	echo "src/form/form-atelier/template.ts\n";
}

$parts = array( 'axellcore-header' => 'header-part.html', 'axellcore-footer' => 'footer-part.html' );
foreach ( $parts as $slug => $file ) {
	$part = get_posts( array( 'post_type' => 'wp_template_part', 'name' => $slug, 'post_status' => 'any', 'numberposts' => 1 ) );
	if ( $part ) {
		file_put_contents( $dir . $file, $part[0]->post_content );
		echo $file . "\n";
	}
}

// Media used by the exported content (images with a wp-image-{id} class):
// the files go to media/ and media.json keeps the id and URL they had here,
// so Activator can import them on a clean install and point the content at
// the new attachments.
$exported = '';
foreach ( glob( $dir . '{*.html,pages/*.html,pages/*/*.html,pages/*/*/*.html}', GLOB_BRACE ) as $html ) {
	$exported .= file_get_contents( $html );
}
preg_match_all( '/\bwp-image-(\d+)\b/', $exported, $found );
$media_dir = $dir . 'media/';
if ( ! is_dir( $media_dir ) ) {
	mkdir( $media_dir, 0755, true );
}
foreach ( glob( $media_dir . '*' ) as $stale ) {
	unlink( $stale );
}
$media = array();
foreach ( array_unique( array_map( 'intval', $found[1] ) ) as $id ) {
	$file = get_attached_file( $id );
	if ( ! $file || ! file_exists( $file ) ) {
		echo "media {$id} missing\n";
		continue;
	}
	copy( $file, $media_dir . basename( $file ) );
	update_post_meta( $id, '_axellcore_atelierclub_media', basename( $file ) );
	$media[] = array(
		'file'  => basename( $file ),
		'id'    => $id,
		'url'   => wp_get_attachment_url( $id ),
		'title' => get_the_title( $id ),
		'alt'   => (string) get_post_meta( $id, '_wp_attachment_image_alt', true ),
	);
	echo 'media/' . basename( $file ) . "\n";
}
// Navigation menus the content references ("ref" of a navigation block): the
// menu content goes to navigation/{slug}.html and navigation.json keeps the id
// it had here, so Activator can create it and fix the "ref".
preg_match_all( '/<!-- wp:navigation (\{.*?\}) \/?-->/', $exported, $navs );
$nav_dir = $dir . 'navigation/';
if ( ! is_dir( $nav_dir ) ) {
	mkdir( $nav_dir, 0755, true );
}
foreach ( glob( $nav_dir . '*' ) as $stale ) {
	unlink( $stale );
}
$navigation = array();
foreach ( $navs[1] as $json ) {
	$attrs = json_decode( $json, true );
	$menu  = ! empty( $attrs['ref'] ) ? get_post( (int) $attrs['ref'] ) : null;
	if ( ! $menu || 'wp_navigation' !== $menu->post_type || isset( $navigation[ $menu->ID ] ) ) {
		continue;
	}
	$file = $menu->post_name . '.html';
	file_put_contents( $nav_dir . $file, $menu->post_content );
	update_post_meta( $menu->ID, '_axellcore_atelierclub_navigation', $file );
	$navigation[ $menu->ID ] = array(
		'file'  => $file,
		'id'    => $menu->ID,
		'title' => $menu->post_title,
	);
	echo 'navigation/' . $file . "\n";
}
file_put_contents( $dir . 'navigation.json', wp_json_encode( array_values( $navigation ), JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES ) . "\n" );
echo "navigation.json\n";

file_put_contents( $dir . 'media.json', wp_json_encode( $media, JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES ) . "\n" );
echo "media.json\n";
PHP
)"

cd "$SITE_DIR"
studio wp eval "$PHP"
